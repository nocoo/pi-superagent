/**
 * The local IM's storage: one append-only JSONL file per channel under `<stateDir>/im`. It is a file format, not an
 * interface — the only supported way to read or write a channel is `pi-superagent chat`. Keeping it a plain file is what
 * lets the agent be down, or a person be in an editor, without losing a message.
 */
import { appendFileSync, existsSync, mkdirSync, readdirSync, readFileSync } from 'node:fs'
import { join } from 'node:path'
import { randomUUID } from 'node:crypto'

/** One message. `kind` separates a person's words from a bot's, which never authorize work on their own. */
export interface ImMessage {
  id: string
  /** The channel name; also the Thread every message in it belongs to. */
  channel: string
  from: string
  at: string
  text: string
  /** The message this one answers, when it answers one. */
  replyTo?: string
  /** A bot's message is `bot`; a person's is omitted. */
  kind?: 'bot'
}

/** A channel name that is safe as a file name. */
export const CHANNEL = /^[a-z0-9][a-z0-9._-]{0,63}$/

/** Throws unless `name` can be a channel. */
export function checkChannel(name: string): string {
  if (!CHANNEL.test(name)) throw new Error(`channel names are lowercase letters, digits, dot, dash and underscore, at most 64 characters; got ${name}`)
  return name
}

/** A new message id, generated by the sender so re-reading the file can never mint a second one. */
export const messageId = (): string => `m-${Date.now().toString(36)}-${randomUUID().slice(0, 8)}`

/** Reads complete lines from `buffer` starting at `offset`, and returns the new offset. A trailing partial line is kept. */
export function readLines(buffer: Buffer, offset: number): { lines: string[]; offset: number } {
  const slice = buffer.subarray(offset)
  const last = slice.lastIndexOf(0x0a)
  if (last < 0) return { lines: [], offset }
  const text = slice.subarray(0, last).toString('utf8')
  return { lines: text.split('\n').filter(line => line.trim()), offset: offset + last + 1 }
}

/** The IM's directory and its channels. */
export class ImStore {
  constructor(readonly root: string) {}

  /** Creates the directory if it is missing; only the chat command and a Source that listens do this. */
  ensure(): void { mkdirSync(this.root, { recursive: true, mode: 0o700 }) }

  /** Absolute path of a channel's file. */
  path(channel: string): string { return join(this.root, `${checkChannel(channel)}.jsonl`) }

  /** Channel names that have a file, sorted. */
  channels(): string[] {
    if (!existsSync(this.root)) return []
    return readdirSync(this.root).filter(name => name.endsWith('.jsonl'))
      .map(name => name.slice(0, -'.jsonl'.length)).filter(name => CHANNEL.test(name)).sort()
  }

  /** Appends one message; the file is created when it does not exist. */
  append(message: ImMessage): void {
    this.ensure()
    appendFileSync(this.path(message.channel), `${JSON.stringify(message)}\n`, { mode: 0o600 })
  }

  /** Every message of a channel, oldest first; a malformed line is skipped rather than failing the read. */
  messages(channel: string): ImMessage[] {
    const path = this.path(channel)
    if (!existsSync(path)) return []
    return readFileSync(path, 'utf8').split('\n').flatMap(line => {
      if (!line.trim()) return []
      try { return [JSON.parse(line) as ImMessage] } catch { return [] }
    })
  }

  /** The file's size, which is how a Source knows whether it has read everything. */
  size(channel: string): number {
    const path = this.path(channel)
    return existsSync(path) ? readFileSync(path).length : 0
  }
}
